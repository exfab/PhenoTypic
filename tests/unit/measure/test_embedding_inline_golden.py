"""The inline ``MeasureDinoEmbedding`` golden, captured on the #281 merge (#282 P0 T2).

#282 P1 refactors the embedder into a loader plus a batch encoder and must keep
every byte it writes. This file pins those bytes **before** the refactor: the
float16 vectors, the Parquet table the writer produces, and the payload
descriptor, for six pipelines on the parametric stub backbone
(``tests/_tiny_run.py``), all with ``device="cpu"``.

Regenerate with ``PHENOTYPIC_REGEN_GOLDEN=1``; the run then fails on purpose
("golden regenerated; commit it"), so a regeneration is never silently green.
The real-backbone rows need the cached ``facebook/dinov2-small`` weights and
are ``slow``; they are regenerated by the same variable.

**The bytes belong to one CPU environment.** float32 kernels round
differently by CPU family and by torch's threading (#282 C3 gate,
``gate-results/c3-282/diag`` and ``capture``): the five stub rows with a
learned layer differ on Cascade Lake and Milan; the real rows differ at 8
threads, and even at 4 when ``torch.set_num_threads(4)`` is called rather than
taken from ``OMP_NUM_THREADS=4``. So the byte-identity tests change nothing
about threading: they **skip**, naming both environments, unless the CPU
model, torch build, ``OMP_NUM_THREADS`` and ``torch.get_num_threads()`` are the
recorded ones (``inline_embeddings_281.environment.json``). Run them on a
Broadwell node (``--constraint=broadwell``) with ``--cpus-per-task=4`` and
``OMP_NUM_THREADS=4``. A separate, always-on check compares every row's vector
with the stored ones (``inline_embeddings_281.vectors.npz``) by cosine, so a
node that cannot check bytes still catches drift.
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import numpy as np
import pytest

from tests._tiny_run import inline_golden_cases, install_stub_backbone

GOLDEN = Path(__file__).parent / "golden" / "inline_embeddings_281.json"
#: The CPU model, torch build and thread count the golden's bytes reproduce in.
ENVIRONMENT = GOLDEN.with_name("inline_embeddings_281.environment.json")
#: Each row's float16 vectors, ``<case>|<payload key, / as |>``.
VECTORS = GOLDEN.with_name("inline_embeddings_281.vectors.npz")
REGENERATING = os.environ.get("PHENOTYPIC_REGEN_GOLDEN") == "1"

#: The always-on check's floor: every row's cosine to its golden vector.
COSINE_FLOOR = 1 - 1e-6

#: The environment fields that must match for the bytes to be checked.
_BYTE_ENVIRONMENT = ("cpu_model", "torch_version", "omp_num_threads", "torch_num_threads")

#: Descriptor fields the golden leaves out: ``model.device`` and
#: ``model.device_name`` are provenance; ``compute`` and ``compute_dtype`` are
#: added by P2 T1, after the golden is captured.
_MODEL_PROVENANCE = ("device", "device_name")
_ADDED_BY_P2 = ("compute", "compute_dtype")


def golden_record(payload) -> dict:
    """The three pinned fields of one payload."""
    from phenotypic.sdk_._embedding_tables import (
        _write_embedding_parquet,
        embedding_arrow_table,
    )

    vectors = np.stack(payload.frame["embedding"].to_list()).astype(np.float16)
    descriptor = json.loads(json.dumps(payload.descriptor, default=str))
    for field in _ADDED_BY_P2:
        descriptor.pop(field, None)
    for field in _MODEL_PROVENANCE:
        descriptor["model"].pop(field, None)
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "table.parquet"
        _write_embedding_parquet(path, embedding_arrow_table(payload), payload.dim)
        table_sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
    return {
        "vectors_sha256": hashlib.sha256(np.ascontiguousarray(vectors).tobytes()).hexdigest(),
        "table_sha256": table_sha256,
        "descriptor": descriptor,
    }


def _records(payloads) -> dict:
    return {key: golden_record(payload) for key, payload in payloads.items()}


def _load_golden() -> dict:
    return json.loads(GOLDEN.read_text(encoding="utf-8"))


def _store_golden(updates: dict, payloads_by_case: dict) -> None:
    """Write *updates*, their vectors and this process's environment; then fail."""
    golden = _load_golden() if GOLDEN.exists() else {}
    golden.update(updates)
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(json.dumps(golden, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    vectors = dict(np.load(VECTORS)) if VECTORS.exists() else {}
    for case, payloads in payloads_by_case.items():
        for key, payload in payloads.items():
            vectors[_vector_key(case, key)] = _stored(payload)
    np.savez_compressed(VECTORS, **vectors)
    ENVIRONMENT.write_text(
        json.dumps(current_environment(), indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    pytest.fail("golden regenerated; commit it")


def _stored(payload) -> np.ndarray:
    return np.stack(payload.frame["embedding"].to_list()).astype(np.float16)


def _vector_key(case: str, key: str) -> str:
    return f"{case}|{key.replace('/', '|')}"


def _cpu_model() -> str | None:
    """The first ``model name`` of ``/proc/cpuinfo``; ``None`` where there is none."""
    try:
        text = Path("/proc/cpuinfo").read_text(encoding="utf-8")
    except OSError:
        return None
    for line in text.splitlines():
        if line.startswith("model name"):
            return line.split(":", 1)[1].strip()
    return None


def current_environment() -> dict:
    """This process's CPU model, torch build, ``OMP_NUM_THREADS`` and torch thread count."""
    import torch

    return {
        "cpu_model": _cpu_model(),
        "torch_version": torch.__version__,
        "omp_num_threads": os.environ.get("OMP_NUM_THREADS"),
        "torch_num_threads": torch.get_num_threads(),
        "cpu_capability": torch.backends.cpu.get_cpu_capability(),
    }


def _recorded_environment() -> dict:
    return json.loads(ENVIRONMENT.read_text(encoding="utf-8"))


def _skip_unless_capture_environment() -> None:
    """Skip a byte-identity check off the capture environment, naming both."""
    if REGENERATING:
        return
    recorded, here = _recorded_environment(), current_environment()
    differing = [field for field in _BYTE_ENVIRONMENT if recorded[field] != here[field]]
    if differing:
        pytest.skip(
            "golden bytes reproduce only in their capture environment, "
            + ", ".join(f"{field}={recorded[field]!r}" for field in _BYTE_ENVIRONMENT)
            + f" (node {recorded.get('slurm_node')}); this is "
            + ", ".join(f"{field}={here[field]!r}" for field in _BYTE_ENVIRONMENT)
            + ". Run on --constraint=broadwell with OMP_NUM_THREADS=4; the cosine "
            "check runs regardless."
        )


def _assert_near_golden(case: str, payloads) -> None:
    """Every row's vector is within :data:`COSINE_FLOOR` of the stored one."""
    stored = np.load(VECTORS)
    for key, payload in payloads.items():
        got = _stored(payload).astype(np.float64)
        want = stored[_vector_key(case, key)].astype(np.float64)
        assert got.shape == want.shape, (case, key)
        norms = np.linalg.norm(got, axis=1) * np.linalg.norm(want, axis=1)
        dots = np.einsum("ij,ij->i", got, want)
        cosine = np.where(norms > 0, dots / np.where(norms > 0, norms, 1), 1.0)
        assert cosine.min() >= COSINE_FLOOR, (case, key, float(1 - cosine.min()))


def _stub_registers(case: str) -> int:
    return 4 if case == "registers_mean" else 0


def _stub_payloads(case, monkeypatch, plate):
    install_stub_backbone(
        monkeypatch, parametric=True, num_register_tokens=_stub_registers(case)
    )
    return inline_golden_cases()[case].embed(plate)


@pytest.mark.parametrize("case", sorted(inline_golden_cases()))
def test_inline_bytes_match_the_281_golden(case, monkeypatch, detected_plate):
    pytest.importorskip("torch")
    _skip_unless_capture_environment()
    payloads = _stub_payloads(case, monkeypatch, detected_plate)
    if REGENERATING:
        _store_golden({case: _records(payloads)}, {case: payloads})
    expected = _load_golden()[case]
    assert sorted(payloads) == sorted(expected)
    for key, payload in payloads.items():
        assert golden_record(payload) == expected[key], key


@pytest.mark.parametrize("case", sorted(inline_golden_cases()))
def test_inline_vectors_are_near_the_281_golden(case, monkeypatch, detected_plate):
    """Always on, any CPU: each row's cosine to the golden vector is >= 1 - 1e-6."""
    pytest.importorskip("torch")
    _assert_near_golden(case, _stub_payloads(case, monkeypatch, detected_plate))


def test_the_registers_case_differs_from_a_registerless_run(monkeypatch, detected_plate):
    pytest.importorskip("torch")
    vectors = []
    for registers in (0, 4):
        install_stub_backbone(monkeypatch, parametric=True, num_register_tokens=registers)
        payloads = inline_golden_cases()["registers_mean"].embed(detected_plate)
        vectors.append(golden_record(next(iter(payloads.values())))["vectors_sha256"])
    assert vectors[0] != vectors[1]  # the golden row can fail on a register bug


_REAL_CASES = ("objects_cls", "objects_mean_masked", "objects_dense")


def _small_is_cached() -> bool:
    import importlib.util

    if importlib.util.find_spec("torch") is None or importlib.util.find_spec("transformers") is None:
        return False
    from phenotypic.detect.nn._helper._checkpoint_manager import hf_repo_is_cached

    return bool(hf_repo_is_cached("facebook/dinov2-small"))


_REAL_KWARGS = {
    "objects_cls": {},
    "objects_mean_masked": {
        "pooling": "crop_mean", "mask_background": True, "crop_pad_frac": 0.5,
    },
    "objects_dense": {"pooling": "masked_dense", "crop_px": 112},
}


@pytest.fixture(scope="module")
def real_small_payloads():
    """Real DINOv2-small, CPU: computed once per module, threading left untouched.

    Run anonymously (``HF_HUB_DISABLE_IMPLICIT_TOKEN=1``) for this public repo.
    """
    from phenotypic import ImagePipeline
    from phenotypic.data import load_synth_yeast_plate
    from phenotypic.detect import OtsuDetector
    from phenotypic.measure import MeasureDinoEmbedding
    from phenotypic.measure import _measure_dino_embedding as module

    plate = OtsuDetector().apply(load_synth_yeast_plate())
    module._cached_backbone.cache_clear()
    try:
        payloads = {}
        for case in _REAL_CASES:
            pipe = ImagePipeline(
                meas={"emb": MeasureDinoEmbedding(size="small", device="cpu", **_REAL_KWARGS[case])}
            )
            payloads[f"real_small_{case}"] = pipe.embed(plate)
    finally:
        module._cached_backbone.cache_clear()
    return payloads


_REQUIRES_SMALL = pytest.mark.skipif(
    not _small_is_cached(),
    reason="Requires torch, transformers and cached facebook/dinov2-small weights",
)


@pytest.mark.slow
@_REQUIRES_SMALL
def test_real_small_backbone_matches_the_golden(real_small_payloads):
    """Real DINOv2-small, CPU: ``crop_cls``, ``crop_mean`` and the processor's dense path."""
    _skip_unless_capture_environment()
    records = {case: _records(payloads) for case, payloads in real_small_payloads.items()}
    if REGENERATING:
        _store_golden(records, real_small_payloads)
    expected = _load_golden()
    for case, record in records.items():
        assert record == expected[case], case


@pytest.mark.slow
@_REQUIRES_SMALL
def test_real_small_vectors_are_near_the_golden(real_small_payloads):
    """Any CPU: each real row's cosine to the golden vector is >= 1 - 1e-6."""
    for case, payloads in real_small_payloads.items():
        _assert_near_golden(case, payloads)
