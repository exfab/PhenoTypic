"""The inline ``MeasureDinoEmbedding`` golden, captured on the #281 merge (#282 P0 T2).

#282 P1 refactors the embedder into a loader plus a batch encoder and must keep
every byte it writes. This file pins those bytes **before** the refactor: the
float16 vectors, the Parquet table the writer produces, and the payload
descriptor, for six pipelines on the parametric stub backbone
(``tests/_tiny_run.py``), all with ``device="cpu"``.

Regenerate with ``PHENOTYPIC_REGEN_GOLDEN=1``; the run then fails on purpose
("golden regenerated; commit it"), so a regeneration is never silently green.
The real-backbone rows need the cached ``facebook/dinov2-small`` weights and
are ``slow``; they are regenerated by the same variable.
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import numpy as np
import pytest

from tests._tiny_run import inline_golden_cases, install_stub_backbone

GOLDEN = Path(__file__).parent / "golden" / "inline_embeddings_281.json"
REGENERATING = os.environ.get("PHENOTYPIC_REGEN_GOLDEN") == "1"

#: Descriptor fields the golden leaves out: ``model.device`` and
#: ``model.device_name`` are provenance; ``compute`` and ``compute_dtype`` are
#: added by P2 T1, after the golden is captured.
_MODEL_PROVENANCE = ("device", "device_name")
_ADDED_BY_P2 = ("compute", "compute_dtype")


def golden_record(payload) -> dict:
    """The three pinned fields of one payload."""
    from phenotypic.sdk_._embedding_tables import (
        _write_embedding_parquet,
        embedding_arrow_table,
    )

    vectors = np.stack(payload.frame["embedding"].to_list()).astype(np.float16)
    descriptor = json.loads(json.dumps(payload.descriptor, default=str))
    for field in _ADDED_BY_P2:
        descriptor.pop(field, None)
    for field in _MODEL_PROVENANCE:
        descriptor["model"].pop(field, None)
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "table.parquet"
        _write_embedding_parquet(path, embedding_arrow_table(payload), payload.dim)
        table_sha256 = hashlib.sha256(path.read_bytes()).hexdigest()
    return {
        "vectors_sha256": hashlib.sha256(np.ascontiguousarray(vectors).tobytes()).hexdigest(),
        "table_sha256": table_sha256,
        "descriptor": descriptor,
    }


def _records(payloads) -> dict:
    return {key: golden_record(payload) for key, payload in payloads.items()}


def _load_golden() -> dict:
    return json.loads(GOLDEN.read_text(encoding="utf-8"))


def _store_golden(updates: dict) -> None:
    golden = _load_golden() if GOLDEN.exists() else {}
    golden.update(updates)
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    GOLDEN.write_text(json.dumps(golden, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    pytest.fail("golden regenerated; commit it")


def _stub_registers(case: str) -> int:
    return 4 if case == "registers_mean" else 0


@pytest.mark.parametrize("case", sorted(inline_golden_cases()))
def test_inline_bytes_match_the_281_golden(case, monkeypatch, detected_plate):
    pytest.importorskip("torch")
    install_stub_backbone(
        monkeypatch, parametric=True, num_register_tokens=_stub_registers(case)
    )
    payloads = inline_golden_cases()[case].embed(detected_plate)
    if REGENERATING:
        _store_golden({case: _records(payloads)})
    expected = _load_golden()[case]
    assert sorted(payloads) == sorted(expected)
    for key, payload in payloads.items():
        assert golden_record(payload) == expected[key], key


def test_the_registers_case_differs_from_a_registerless_run(monkeypatch, detected_plate):
    pytest.importorskip("torch")
    vectors = []
    for registers in (0, 4):
        install_stub_backbone(monkeypatch, parametric=True, num_register_tokens=registers)
        payloads = inline_golden_cases()["registers_mean"].embed(detected_plate)
        vectors.append(golden_record(next(iter(payloads.values())))["vectors_sha256"])
    assert vectors[0] != vectors[1]  # the golden row can fail on a register bug


_REAL_CASES = ("objects_cls", "objects_mean_masked", "objects_dense")


def _small_is_cached() -> bool:
    import importlib.util

    if importlib.util.find_spec("torch") is None or importlib.util.find_spec("transformers") is None:
        return False
    from phenotypic.detect.nn._helper._checkpoint_manager import hf_repo_is_cached

    return bool(hf_repo_is_cached("facebook/dinov2-small"))


@pytest.mark.slow
@pytest.mark.skipif(
    not _small_is_cached(),
    reason="Requires torch, transformers and cached facebook/dinov2-small weights",
)
def test_real_small_backbone_matches_the_golden(detected_plate):
    """Real DINOv2-small, CPU: ``crop_cls``, ``crop_mean`` and the processor's dense path.

    Run anonymously (``HF_HUB_DISABLE_IMPLICIT_TOKEN=1``) for this public repo.
    """
    from phenotypic import ImagePipeline
    from phenotypic.measure import MeasureDinoEmbedding
    from phenotypic.measure import _measure_dino_embedding as module

    module._cached_backbone.cache_clear()
    kwargs = {
        "objects_cls": {},
        "objects_mean_masked": {
            "pooling": "crop_mean", "mask_background": True, "crop_pad_frac": 0.5,
        },
        "objects_dense": {"pooling": "masked_dense", "crop_px": 112},
    }
    records = {}
    for case in _REAL_CASES:
        pipe = ImagePipeline(
            meas={"emb": MeasureDinoEmbedding(size="small", device="cpu", **kwargs[case])}
        )
        records[f"real_small_{case}"] = _records(pipe.embed(detected_plate))
    if REGENERATING:
        _store_golden(records)
    expected = _load_golden()
    for case, record in records.items():
        assert record == expected[case], case
