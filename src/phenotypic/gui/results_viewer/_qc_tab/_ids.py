"""Component IDs owned by the QC tab.

The QC tab body composes:

* a top strip with ``+ Add check`` / ``Export QC report`` buttons and a
  success toast;
* a load-warning banner mounted via :data:`QC_LOAD_WARNING_BANNER_ID`
  (visibility toggled by the layout factory based on
  :class:`~phenotypic.sdk_._qc_recipe.QcRecipe.load_warnings`);
* a cards container hosting one ``dbc.Card`` per enabled QC entry; the
  cards themselves use pattern-matching ids keyed by ``instance_id``;
* a single ``dbc.Modal`` shared by the add / edit / duplicate flows.

The pattern-matching id helpers match the shapes documented at
spec lines 868-877 so callbacks can use ``MATCH`` / ``ALL`` against
each ``type``.
"""

from __future__ import annotations

from typing import Dict


# ---------------------------------------------------------------------------
# Static component IDs
# ---------------------------------------------------------------------------

#: Parent ``<div>`` wrapping every QC check card. Atomically rewritten
#: by the card-list-render callback on every recipe-revision tick so the
#: number of card shells always matches the recipe.
QC_CARDS_CONTAINER_ID: str = "qc-cards-container"

#: ``+ Add check`` button on the top strip. Opens the shared QC modal in
#: "add" mode (``STORE_QC_EDITING_INSTANCE`` is reset to ``None``).
QC_ADD_CHECK_BTN_ID: str = "qc-add-check-btn"

#: ``Export QC report`` button on the top strip. Disabled when no checks
#: are enabled; writes ``qc.parquet`` + ``qc_summary.json`` into
#: ``deliverables/qc/`` (via ``OutputRoot.layout.qc_dir``) on click.
QC_EXPORT_BTN_ID: str = "qc-export-btn"

#: Success/failure toast displayed after the export button completes.
#: The body carries the absolute paths written.
QC_EXPORT_TOAST_ID: str = "qc-export-toast"

#: Banner ``<div>`` rendered above the cards container when the recipe
#: failed to resolve one or more entries at load time. Visibility (via
#: ``style.display``) is owned by the card-list-render callback so the
#: banner re-appears if the user installs a new recipe with warnings.
QC_LOAD_WARNING_BANNER_ID: str = "qc-load-warning-banner"


# ---------------------------------------------------------------------------
# Shared modal (add + edit + duplicate flows)
# ---------------------------------------------------------------------------

#: Root ``dbc.Modal`` shared by every modal-driven flow (add / edit /
#: duplicate). Mounted once in the QC tab body and never re-rendered.
QC_MODAL_ID: str = "qc-add-check-modal"

#: Title ``dbc.ModalTitle`` text. Swapped between "Add QC check" and
#: "Edit QC check" by the modal-open callback.
QC_MODAL_TITLE_ID: str = "qc-add-check-modal-title"

#: Class-picker ``dcc.Dropdown`` populated from
#: ``OperationRegistry.get_by_category("quality_check")``.
QC_MODAL_CLASS_PICKER_ID: str = "qc-add-check-class-picker"

#: ``<div>`` re-rendered with a fresh ``param_form`` whenever the class
#: dropdown changes. Holds the pattern-matched param widgets.
QC_MODAL_PARAMS_REGION_ID: str = "qc-add-check-params-region"

#: ``Save`` button inside the modal footer. Fires the add/update
#: callback.
QC_MODAL_SUBMIT_BTN_ID: str = "qc-add-check-submit"

#: ``Cancel`` button inside the modal footer. Closes the modal without
#: writing.
QC_MODAL_CANCEL_BTN_ID: str = "qc-add-check-cancel"

#: Hidden ``dcc.Store`` holding the ``instance_id`` of the entry the
#: modal is currently editing (``None`` in add mode). The submit
#: callback reads this to decide between :meth:`QcRecipe.add` and
#: :meth:`QcRecipe.update`.
STORE_QC_EDITING_INSTANCE: str = "store-qc-editing-instance"

#: Hidden ``dcc.Store`` ticked by the settings-edit recompute callback
#: after a full ``run_qc`` rebuild of ``qc.duckdb``. The Review worklist
#: subscribes to it so the worklist + summary header re-render off the
#: freshly-rewritten database whenever a check's settings change (even when
#: the selected module's ``instance_id`` is unchanged).
STORE_QC_RECOMPUTE_DONE: str = "store-qc-recompute-done"


# ---------------------------------------------------------------------------
# Pattern-matching id-builders — per-card components
# ---------------------------------------------------------------------------


def qc_card_root_id(instance_id: str) -> Dict[str, str]:
    """Build the pattern-matching id for a QC check card's root container.

    Args:
        instance_id: The recipe entry's ``instance_id`` (stable across
            recipe revisions, generated by :meth:`QcRecipe.add`).

    Returns:
        Dict of shape ``{"type": "qc-card-root", "index": instance_id}``.
    """
    return {"type": "qc-card-root", "index": instance_id}


